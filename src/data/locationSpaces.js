const KIND_LABEL = {
  search: 'Search space',
  exit: 'Exit',
  special: 'Special space',
  plain: null,
};

/* Spaces for one location (app location id), named spaces first, then the
   "Between ..." ones, each alphabetically. Shaped like card options:
   { id, name, effect } so the Turn Tracker dropdown can use them directly. */
export function spacesFor(locationId) {
  const list = LOCATION_SPACES[locationId] || [];
  const isBetween = (n) => /^(Between|Beside|Corridor|Road|Corn field) /.test(n);
  return [...list]
    .sort((a, b) => (isBetween(a.name) - isBetween(b.name)) || a.name.localeCompare(b.name))
    .map((s, i) => ({ id: `${locationId}-space-${i}`, name: s.name, effect: KIND_LABEL[s.kind] || null, kind: s.kind }));
}
